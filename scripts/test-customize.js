#!/usr/bin/env node
'use strict';
var assert = require('assert'), p = require('../app/customize.js');
assert.strictEqual(p.isProtected('com.infinitimoney.tvhome'), true);
assert.strictEqual(p.isProtected('com.webos.app.hdmi1'), true);
assert.strictEqual(p.setVisible('com.webos.app.livetv', true), false);
assert.strictEqual(p.isVisible('com.webos.app.livetv', []), false);
assert.strictEqual(p.isVisible('com.netflix.app', []), true);
assert.strictEqual(p.isVisible('shortcutcopilot', ['shortcutcopilot']), false);
assert.strictEqual(p.setVisible('shortcutcopilot', true), true);
assert.strictEqual(p.isVisible('shortcutcopilot', ['shortcutcopilot']), true);
assert.strictEqual(p.setVisible('com.netflix.app', false), true);
assert.strictEqual(p.isVisible('com.netflix.app', []), false);
p.resetVisible();
assert.strictEqual(p.isVisible('shortcutcopilot', ['shortcutcopilot']), false);
assert.strictEqual(p.getAppearance().theme, 'midnight');
assert.strictEqual(p.saveAppearance({theme:'ocean', font:'sans', showWeek:false}).theme, 'ocean');
assert.strictEqual(p.getAppearance().showWeek, false);
assert.strictEqual(p.saveAppearance({theme:'unknown'}).theme, 'midnight');
assert.strictEqual(p.getAppearance().showSolar, true);
assert.strictEqual(p.getAppearance().showLunar, true);
assert.strictEqual(p.saveAppearance({reduceMotion:true, showSolar:false}).reduceMotion, true);
assert.strictEqual(p.getAppearance().showSolar, false);
assert.strictEqual(p.saveAppearance({reduceMotion:false, showSolar:true, showLunar:false}).showLunar, false);
assert.strictEqual(p.validCoords(21.0285,105.8542), true);
assert.strictEqual(p.validCoords(0,0), true);
assert.strictEqual(p.validCoords(99,105), false);
assert.strictEqual(p.validCoords(NaN,106), false);
assert.strictEqual(p.saveWeather({place:'Hà Nội',latitude:21.0285,longitude:105.8542,enabled:true}).enabled,true);
assert.strictEqual(p.getWeather().place, 'Hà Nội');
assert.strictEqual(p.getWeather().latitude, 21.0285);
assert.strictEqual(p.saveWeather({latitude:900}),false);
assert.strictEqual(p.getWeather().latitude,21.0285);
assert.strictEqual(p.saveWeather({enabled:false}).enabled,false);
assert.strictEqual(p.getAIEnabled(),true,'existing installations start with AI available');
assert.strictEqual(p.setAIEnabled(false),false);
assert.strictEqual(p.getAIEnabled(),false);
assert.strictEqual(p.setAIEnabled(true),true);
assert.strictEqual(p.getAIEnabled(),true);
console.log('Customization, AI toggle, calendar, region selection and app visibility tests passed.');
